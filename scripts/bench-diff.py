#!/usr/bin/env python3
"""Compare a garret-bench results file against the checked-in baseline
(spec 09). Reports deltas for every numeric metric; judgement stays with the
human — the only hard failures are failed requests in the new run, an
environment mismatch, because a laptop number diffed against a sandbox
number is noise dressed up as a regression, and a corpus-version mismatch,
because then the two runs pushed different bytes."""

import json
import sys


# Fields that tell the entries of a scenario's result array apart, so a step
# is diffed against the same step even when the runs swept different steps.
STEP_KEYS = {"stream": ("size_bytes",), "pull": ("concurrency", "keepalive")}


def step_label(entry, keys):
    return ",".join(f"{k}={json.dumps(entry.get(k))}" for k in keys)


def flatten(value, prefix=""):
    if isinstance(value, dict):
        for k, v in value.items():
            yield from flatten(v, f"{prefix}{k}.")
    elif isinstance(value, list):
        keys = STEP_KEYS.get(prefix.rstrip("."))
        for i, v in enumerate(value):
            if keys and isinstance(v, dict):
                rest = {k: x for k, x in v.items() if k not in keys}
                yield from flatten(rest, f"{prefix.rstrip('.')}[{step_label(v, keys)}].")
            else:
                yield from flatten(v, f"{prefix}{i}.")
    elif isinstance(value, bool):
        pass
    elif isinstance(value, (int, float)):
        yield prefix.rstrip("."), value


def main():
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} <baseline.json> <current.json>")
    baseline_path, current_path = sys.argv[1], sys.argv[2]
    baseline = json.load(open(baseline_path))
    current = json.load(open(current_path))

    labels = (baseline.get("meta", {}).get("label"), current.get("meta", {}).get("label"))
    if labels[0] != labels[1]:
        sys.exit(
            f"environment mismatch: baseline is '{labels[0]}', current is '{labels[1]}'\n"
            "these runs are not comparable; record a baseline for this environment instead"
        )

    # Results from before meta.corpus_version existed were generated by v1.
    versions = tuple(r.get("meta", {}).get("corpus_version", 1) for r in (baseline, current))
    if versions[0] != versions[1]:
        sys.exit(
            f"corpus mismatch: baseline is corpus v{versions[0]}, current is v{versions[1]}\n"
            "the runs pushed different data; regenerate the baseline with `just bench-baseline`"
        )

    base = dict(flatten(baseline))
    curr = dict(flatten(current))
    skip = ("meta.seed", "meta.corpus_version", "meta.timestamp_unix", "meta.cpus")

    print(f"{'metric':<52} {'baseline':>14} {'current':>14} {'delta':>9}")
    for key in sorted(set(base) | set(curr)):
        if key.startswith(skip):
            continue
        b, c = base.get(key), curr.get(key)
        if b is None or c is None:
            print(f"{key:<52} {b if b is not None else '—':>14} "
                  f"{c if c is not None else '—':>14} {'new' if b is None else 'gone':>9}")
            continue
        delta = f"{(c - b) / b:+8.1%}" if b else "     n/a"
        fmt = lambda v: f"{v:>14.2f}" if isinstance(v, float) else f"{v:>14}"
        print(f"{key:<52} {fmt(b)} {fmt(c)} {delta}")

    failures = sum(v for k, v in curr.items() if k.endswith(".failed"))
    if failures:
        sys.exit(f"\nFAIL: the current run has {int(failures)} failed request(s)")
    print("\nzero failures; latency/throughput judgement is yours")


if __name__ == "__main__":
    main()
